// ── POST /api/setup/test-key ──────────────────────────────────────────────────
// Live-test an API key for a given provider. Requires setup bearer token.
router.post('/test-key', setupLimiter, asyncHandler(async (req, res) => {
  if (!(await verifySetupToken(req))) {
    return res.status(401).json({ error: 'Unauthorized' });
  }
  const { provider, key } = req.body || {};
  if (!provider || typeof provider !== 'string') {
    return res.status(400).json({ error: 'provider required' });
  }

  const start = Date.now();
  const timeout = 8000;
  // AbortSignal.timeout is available in Node 17.3+
  const signal = typeof AbortSignal !== 'undefined' && AbortSignal.timeout
    ? AbortSignal.timeout(timeout)
    : undefined;

  try {
    let detail = '';

    if (provider === 'gemini') {
      if (!key) return res.status(400).json({ error: 'key required' });
      const r = await fetch(
        `https://generativelanguage.googleapis.com/v1beta/models?key=${encodeURIComponent(key)}&pageSize=1`,
        { signal }
      );
      if (!r.ok) {
        const body = await r.json().catch(() => ({}));
        return res.json({ ok: false, provider, latency_ms: Date.now() - start, error: body?.error?.message || `HTTP ${r.status}` });
      }
      const data = await r.json().catch(() => ({}));
      detail = data.models?.length ? `${data.models.length}+ models available` : 'Connected';
    }

    else if (provider === 'openai') {
      if (!key) return res.status(400).json({ error: 'key required' });
      const r = await fetch('https://api.openai.com/v1/models?limit=1', {
        headers: { 'Authorization': `Bearer ${key}` }, signal,
      });
      if (!r.ok) {
        const body = await r.json().catch(() => ({}));
        return res.json({ ok: false, provider, latency_ms: Date.now() - start, error: body?.error?.message || `HTTP ${r.status}` });
      }
      detail = 'OpenAI connected';
    }

    else if (provider === 'anthropic') {
      if (!key) return res.status(400).json({ error: 'key required' });
      const r = await fetch('https://api.anthropic.com/v1/models', {
        headers: { 'x-api-key': key, 'anthropic-version': '2023-06-01' }, signal,
      });
      if (!r.ok) {
        const body = await r.json().catch(() => ({}));
        return res.json({ ok: false, provider, latency_ms: Date.now() - start, error: body?.error?.message || `HTTP ${r.status}` });
      }
      detail = 'Anthropic connected';
    }

    else if (provider === 'openrouter') {
      if (!key) return res.status(400).json({ error: 'key required' });
      const r = await fetch('https://openrouter.ai/api/v1/models?per_page=1', {
        headers: { 'Authorization': `Bearer ${key}` }, signal,
      });
      if (!r.ok) {
        const body = await r.json().catch(() => ({}));
        return res.json({ ok: false, provider, latency_ms: Date.now() - start, error: body?.error?.message || `HTTP ${r.status}` });
      }
      detail = 'OpenRouter connected';
    }

    else if (provider === 'ollama') {
      const baseUrl = (key || 'http://localhost:11434').replace(/\/$/, '');
      const r = await fetch(`${baseUrl}/api/tags`, { signal });
      if (!r.ok) {
        return res.json({ ok: false, provider, latency_ms: Date.now() - start, error: `HTTP ${r.status} — is Ollama running at ${baseUrl}?` });
      }
      const data = await r.json().catch(() => ({}));
      const n = data.models?.length || 0;
      detail = `Ollama connected · ${n} model${n !== 1 ? 's' : ''} installed`;
    }

    else if (provider === 'elevenlabs') {
      if (!key) return res.status(400).json({ error: 'key required' });
      // Try subscription endpoint first; fall back to /voices which all key types can access
      let r = await fetch('https://api.elevenlabs.io/v1/user/subscription', {
        headers: { 'xi-api-key': key }, signal,
      });
      if (!r.ok) {
        r = await fetch('https://api.elevenlabs.io/v1/voices', {
          headers: { 'xi-api-key': key },
          signal: typeof AbortSignal !== 'undefined' && AbortSignal.timeout ? AbortSignal.timeout(5000) : undefined,
        });
        if (!r.ok) {
          const body = await r.json().catch(() => ({}));
          return res.json({ ok: false, provider, latency_ms: Date.now() - start, error: body?.detail?.message || `HTTP ${r.status}` });
        }
        detail = 'ElevenLabs connected';
      } else {
        const data = await r.json().catch(() => ({}));
        detail = data.character_limit
          ? `${(data.character_count || 0).toLocaleString()} / ${data.character_limit.toLocaleString()} chars used`
          : 'ElevenLabs connected';
      }
    }

    else if (provider === 'resend') {
      if (!key) return res.status(400).json({ error: 'key required' });
      const r = await fetch('https://api.resend.com/domains', {
        headers: { 'Authorization': `Bearer ${key}` }, signal,
      });
      if (!r.ok) {
        const body = await r.json().catch(() => ({}));
        return res.json({ ok: false, provider, latency_ms: Date.now() - start, error: body?.message || `HTTP ${r.status}` });
      }
      detail = 'Resend connected';
    }

    else {
      return res.status(400).json({ error: `Unknown provider: ${provider}` });
    }

    res.json({ ok: true, provider, latency_ms: Date.now() - start, detail });
  } catch (err) {
    const isTimeout = err.name === 'TimeoutError' || err.name === 'AbortError';
    res.json({ ok: false, provider, latency_ms: Date.now() - start, error: isTimeout ? 'Request timed out' : err.message });
  }
}));

// ── POST /api/setup/seed-content ──────────────────────────────────────────────
// Seeds default categories, roles, and system agents. Idempotent.
router.post('/seed-content', setupLimiter, asyncHandler(async (req, res) => {
  if (!(await verifySetupToken(req))) {
    return res.status(401).json({ error: 'Unauthorized' });
  }

  const { categories = true, agents = true, roles = true, site_name } = req.body || {};
  const tenantId = req.tenantId || 1;
  const seeded = { categories: 0, roles: 0, agents: [] };

  // Site name
  if (site_name && typeof site_name === 'string' && site_name.trim()) {
    await db.prepare(
      "INSERT INTO settings (tenant_id, key, value) VALUES ($1, 'site_name', $2) ON CONFLICT (tenant_id, key) DO UPDATE SET value = $2"
    ).run(tenantId, site_name.trim().slice(0, 100)).catch(() => {});
  }

  // Categories
  if (categories) {
    for (const cat of DEFAULT_CATEGORIES) {
      try {
        const result = await db.prepare(`
          INSERT INTO categories (tenant_id, name, slug, keywords)
          VALUES ($1, $2, $3, $4::jsonb)
          ON CONFLICT (tenant_id, slug) DO NOTHING
        `).run(tenantId, cat.name, cat.slug, JSON.stringify(cat.keywords));
        if (result?.rowCount > 0) seeded.categories++;
      } catch { /* skip on schema mismatch */ }
    }
  }

  // Roles + default budget settings
  if (roles) {
    for (const role of DEFAULT_SETUP_ROLES) {
      await db.prepare(
        'INSERT INTO roles (tenant_id, name) VALUES ($1, $2) ON CONFLICT DO NOTHING'
      ).run(tenantId, role).catch(() => {});
    }
    seeded.roles = DEFAULT_SETUP_ROLES.length;
    for (const [key, value] of [['ai_daily_budget', '1.00'], ['ai_monthly_budget', '20.00']]) {
      await db.prepare(
        "INSERT INTO settings (tenant_id, key, value) VALUES ($1, $2, $3) ON CONFLICT (tenant_id, key) DO NOTHING"
      ).run(tenantId, key, value).catch(() => {});
    }
  }

  // System agents (Maxwell, Iris, Vera) — lazy-init functions are idempotent
  if (agents) {
    try {
      const { getEditorAgent } = require('../lib/editorial');
      await getEditorAgent(tenantId);
      seeded.agents.push('Maxwell');
    } catch (err) { console.error('[setup/seed] Maxwell:', err.message); }

    try {
      const { ensureDesignerSeeded } = require('../lib/editorial');
      await ensureDesignerSeeded(tenantId);
      seeded.agents.push('Iris');
    } catch (err) { console.error('[setup/seed] Iris:', err.message); }

    try {
      const { getCopyEditorAgent } = require('../lib/copy-editor');
      await getCopyEditorAgent(tenantId);
      seeded.agents.push('Vera');
    } catch (err) { console.error('[setup/seed] Vera:', err.message); }
  }

  res.json({ ok: true, seeded });
}));

// ── POST /api/setup/complete ──────────────────────────────────────────────────
router.post('/complete', asyncHandler(async (req, res) => {
  if (!(await verifySetupToken(req))) {
    return res.status(401).json({ error: 'Unauthorized' });
  }

  const tenantId = req.tenantId || 1;
  try {
    await db.prepare(
      "INSERT INTO settings (tenant_id, key, value) VALUES ($1, 'setup_completed', 'true') ON CONFLICT (tenant_id, key) DO UPDATE SET value = 'true'"
    ).run(tenantId);
    await db.prepare(
      "INSERT INTO settings (tenant_id, key, value) VALUES ($1, 'wizard_completed', 'true') ON CONFLICT (tenant_id, key) DO UPDATE SET value = 'true'"
    ).run(tenantId);
  } catch { /* best effort */ }

  bustSetupCache();
  try {
    const { startAll } = require('../lib/cron-registry');
    await startAll();
    console.log('[setup] Setup complete — cron jobs started');
  } catch (err) {
    console.error('[setup] Failed to start cron jobs:', err.message);
  }

  res.json({ ok: true });
}));

