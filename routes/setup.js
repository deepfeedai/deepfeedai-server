/**
 * Deep Feed AI — routes/setup.js
 * First-boot setup API routes. Only accessible when no admin user exists.
 */
'use strict';

const express        = require('express');
const router         = express.Router();
const bcrypt         = require('bcryptjs');
const jwt            = require('jsonwebtoken');
const rateLimit      = require('express-rate-limit');
const db             = require('../db');
const { asyncHandler }        = require('../lib/utils');
const { isKeyAutoGenerated, getKeyHex } = require('../lib/crypto');
const { getJwtSecret }        = require('../middleware/auth');
const { getDeploymentHealth } = require('../lib/deployment-health');
const tenantUtils              = require('../lib/tenant-utils');
const { getPlatformTenantId } = require('../lib/platform-tenant');
const { isSetupMode, bustSetupCache } = require('../lib/setup-mode');

// Rate limit setup routes to prevent brute-force admin creation
const setupLimiter = rateLimit({
  windowMs: 15 * 60 * 1000,
  max:      10,
  message:  { error: 'Too many setup attempts. Please try again later.' },
});

// ── Guard: only accessible when no admin exists ───────────────────
const requireSetupMode = asyncHandler(async (req, res, next) => {
  if (!(await isSetupMode())) {
    return res.status(403).json({ error: 'Setup already completed. An admin user exists.' });
  }
  next();
});

// ── GET /api/setup/status ─────────────────────────────────────────
router.get('/status', asyncHandler(async (_req, res) => {
  const needsSetup = await isSetupMode();
  const dbReady = db.isDbReady();

  res.json({
    needs_setup: needsSetup,
    version: require('../package.json').version,
    mode: tenantUtils.MULTI_TENANT ? 'multi' : 'single',
    encryption: {
      configured: true, // always true now (auto-generated if not set)
      auto_generated: isKeyAutoGenerated(),
    },
    database: dbReady ? 'connected' : 'not_configured',
  });
}));

// ── POST /api/setup/mode ──────────────────────────────────────────
router.post('/mode', setupLimiter, asyncHandler(async (req, res) => {
  const { mode } = req.body;
  if (!mode || !['single', 'multi'].includes(mode)) {
    return res.status(400).json({ error: 'Mode must be "single" or "multi".' });
  }

  // Set runtime env so MULTI_TENANT getter picks it up immediately
  process.env.DEPLOYMENT_MODE = mode;

  // Persist to settings table so it survives restarts (server.js reads on boot)
  if (db.isDbReady()) {
    const tenantId = req.tenantId || 1;
    await db.prepare(
      "INSERT INTO settings (tenant_id, key, value) VALUES ($1, 'deployment_mode', $2) ON CONFLICT (tenant_id, key) DO UPDATE SET value = $2"
    ).run(tenantId, mode);
  }

  res.json({ ok: true, mode });
}));

// ── POST /api/setup/database ──────────────────────────────────────
router.post('/database', setupLimiter, asyncHandler(async (req, res) => {
  const { url } = req.body;
  if (!url || typeof url !== 'string') {
    return res.status(400).json({ error: 'Database URL is required.' });
  }

  // Basic format validation
  if (!/^postgres(ql)?:\/\/.+/.test(url)) {
    return res.status(400).json({ error: 'URL must start with postgres:// or postgresql://' });
  }

  try {
    await db.connectAndInit(url);
    bustSetupCache(); // re-check setup state now that DB is connected
    res.json({ ok: true, message: 'Database connected and initialized.' });
  } catch (err) {
    res.status(400).json({ error: 'Connection failed: ' + err.message });
  }
}));

// ── POST /api/setup/admin ─────────────────────────────────────────
router.post('/admin', setupLimiter, requireSetupMode, asyncHandler(async (req, res) => {
  const { username, password, email } = req.body;

  if (!username || !password) {
    return res.status(400).json({ error: 'Username and password are required.' });
  }
  if (typeof username !== 'string' || username.length < 3 || username.length > 50) {
    return res.status(400).json({ error: 'Username must be 3-50 characters.' });
  }
  if (typeof password !== 'string' || password.length < 8) {
    return res.status(400).json({ error: 'Password must be at least 8 characters.' });
  }
  // Validate username format
  if (!/^[a-zA-Z0-9_.-]+$/.test(username)) {
    return res.status(400).json({ error: 'Username may only contain letters, numbers, underscores, dots, and hyphens.' });
  }

  const hash = await bcrypt.hash(password, 10);
  const tenantId = await getPlatformTenantId();

  await db.prepare(
    'INSERT INTO users (username, password_hash, email, role, display_name, tenant_id) VALUES ($1, $2, $3, $4, $5, $6)'
  ).run(username, hash, email || null, 'owner', username.charAt(0).toUpperCase() + username.slice(1), tenantId);

  // Look up the created user for JWT
  const user = await db.prepare('SELECT id, username, display_name, email FROM users WHERE username = $1 AND tenant_id = $2').get(username, tenantId);
  const tenant = await db.prepare('SELECT uuid, slug FROM tenants WHERE id = $1').get(tenantId);

  const jwtSecret = await getJwtSecret();
  const token = jwt.sign(
    {
      sub:         user.id,
      username:    user.username,
      displayName: user.display_name,
      email:       user.email,
      tenantId:    tenant?.uuid || tenantId,
      tenantSlug:  tenant?.slug || null,
      role:        'owner',
      type:        'platform-admin',
      authMethod:  'local',
    },
    jwtSecret,
    { expiresIn: '24h' }
  );

  // Bust the setup mode cache so the server exits setup mode
  bustSetupCache();

  res.json({
    token,
    user: {
      id:          user.id,
      username:    user.username,
      displayName: user.display_name,
      email:       user.email,
      role:        'owner',
    },
  });
}));

// ── GET /api/setup/encryption ─────────────────────────────────────
// No requireSetupMode — this runs after admin creation (step 2 → step 3).
// Only exposes the key if auto-generated; safe to call post-admin-creation.
router.get('/encryption', asyncHandler(async (_req, res) => {
  const autoGenerated = isKeyAutoGenerated();
  res.json({
    configured: true,
    auto_generated: autoGenerated,
    // Only expose the key if it was auto-generated (user needs to save it)
    key: autoGenerated ? getKeyHex() : null,
  });
}));

// ── POST /api/setup/complete ──────────────────────────────────────
// No requireSetupMode — called at the end of the wizard after admin creation.
router.post('/complete', asyncHandler(async (req, res) => {
  const tenantId = req.tenantId;
  try {
    await db.prepare(
      "INSERT INTO settings (tenant_id, key, value) VALUES ($1, 'setup_completed', 'true') ON CONFLICT (tenant_id, key) DO UPDATE SET value = 'true'"
    ).run(tenantId);
    // Also mark wizard_completed so the dashboard content wizard banner doesn't appear
    await db.prepare(
      "INSERT INTO settings (tenant_id, key, value) VALUES ($1, 'wizard_completed', 'true') ON CONFLICT (tenant_id, key) DO UPDATE SET value = 'true'"
    ).run(tenantId);
  } catch { /* best effort */ }

  // Bust setup cache and start cron jobs now that setup is done
  bustSetupCache();
  try {
    const { startAll } = require('../lib/cron-registry');
    await startAll();
    console.log('[setup] Setup complete — cron jobs started');
  } catch (err) {
    console.error('[setup] Failed to start cron jobs:', err.message);
  }

  res.json({ ok: true });
}));

// ── GET /api/setup/health ─────────────────────────────────────────
router.get('/health', asyncHandler(async (req, res) => {
  const tenantId = req.tenantId || 1;
  const health = await getDeploymentHealth(tenantId);
  res.json(health);
}));

module.exports = router;
