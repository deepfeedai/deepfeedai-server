// ── POST /api/setup/wizard-complete — marks wizard done, starts cron jobs. Requires admin JWT.
router.post('/wizard-complete', authMiddleware, asyncHandler(async (req, res) => {
  const tenantId = req.tenantId || 1;
  await db.prepare(
    "INSERT INTO settings (tenant_id, key, value) VALUES ($1, 'wizard_completed', '1') ON CONFLICT (tenant_id, key) DO UPDATE SET value = '1'"
  ).run(tenantId);
  await db.prepare(
    "INSERT INTO settings (tenant_id, key, value) VALUES ($1, 'setup_completed', 'true') ON CONFLICT (tenant_id, key) DO UPDATE SET value = 'true'"
  ).run(tenantId);
  bustSetupCache();
  try {
    const { startAll } = require('../lib/cron-registry');
    await startAll();
    console.log('[setup] Wizard complete — cron jobs started');
  } catch (err) {
    console.error('[setup] Failed to start cron jobs:', err.message);
  }
  res.json({ ok: true });
}));

